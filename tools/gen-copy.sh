#!/bin/bash
# gen-copy.sh (Part 3.3) — regenerates docs/copy.md from the Swift
# sources' user-facing string literals (Text/Button/Label/Toggle/
# Picker/Stepper titles and notification copy). There is no String
# Catalog yet; this is the single wording table. Exit non-zero on
# failure. Preflight re-runs it and fails on drift (the checked-in
# file must match the generated one).

set -u
cd "$(dirname "$0")/.."

python3 - <<'PYEOF' > /tmp/gen-copy.md
import re, pathlib

roots = {
    "App": "App",
    "SharedUI": "SharedUI",
}
# (screen guess, text) from common SwiftUI literal calls.
patterns = [
    re.compile(r'Text\("((?:[^"\\]|\\.)+)"\)'),
    re.compile(r'Button\("((?:[^"\\]|\\.)+)"'),
    re.compile(r'Toggle\("((?:[^"\\]|\\.)+)"'),
    re.compile(r'Picker\("((?:[^"\\]|\\.)+)"'),
    re.compile(r'Stepper\(\s*\n?\s*"((?:[^"\\]|\\.)+)"'),
    re.compile(r'content\.title = "((?:[^"\\]|\\.)+)"'),
    re.compile(r'content\.body = "((?:[^"\\]|\\.)+)"'),
]
skip = ("\(Int(", "format:", "EEE", "d MMM", "HH:mm", "%")
rows = {}
for root in ["App", "SharedUI", "Shared", "UsageReport", "UsageMonitor"]:
    for f in pathlib.Path(root).rglob("*.swift"):
        text = f.read_text()
        for i, line in enumerate(text.splitlines(), 1):
            if line.strip().startswith("//"):
                continue
            for pat in patterns:
                for m in pat.findall(line):
                    if any(s in m for s in skip) or "\\(" in m:
                        continue
                    if not m.strip() or m.startswith("of "):
                        continue
                    key = f"{f}:{i}"
                    rows.setdefault(m, []).append(key)

print("# Copy — every user-facing string in the app")
print()
print("Generated by `tools/gen-copy.sh` from the Swift sources; preflight")
print("fails if this table drifts. Edit the wording in the named file,")
print("then run the script to regenerate this page.")
print()
print("| Text | Where |")
print("| --- | --- |")
for text in sorted(rows, key=str.lower):
    where = "; ".join(rows[text][:3])
    print(f"| {text} | `{where}` |")
PYEOF

if [ ! -s /tmp/gen-copy.md ]; then
    echo "gen-copy: nothing generated" >&2
    exit 1
fi
cp /tmp/gen-copy.md docs/copy.md
echo "docs/copy.md regenerated ($(grep -c '^| ' docs/copy.md) table lines)"
